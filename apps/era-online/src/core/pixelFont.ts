/** 掌机方向键等符号使用独立绘制指令，不走字形表。 */
export const SPECIAL: Record<string, 'up' | 'down' | 'left' | 'right'> = {
  '^': 'up',
  v: 'down',
  '<': 'left',
  '>': 'right',
};

function glyphFor(ch: string): Glyph | null {
  if (G[ch]) return G[ch];
  const up = ch.toUpperCase();
  if (G[up]) return G[up];
  return null;
}

/** 字符串的像素宽度（含字间 1px 间隔）。 */
export function measure(text: string, scale = 1): number {
  if (!text.length) return 0;
  return (text.length * (GLYPH_W + 1) - 1) * scale;
}

/**
 * 在 canvas 上绘制点阵文字。
 * 传入的文本会做字形回退：无法识别的字符统一渲染为空白方块，避免出现"缺字即空洞"。
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
): number {
  ctx.fillStyle = color;
  let cx = x;
  for (const raw of text) {
    if (raw === '^' || raw === 'v' || raw === '<' || raw === '>') {
      drawArrow(ctx, SPECIAL[raw]!, cx, y, color, scale);
      cx += (GLYPH_W + 1) * scale;
      continue;
    }
    const g = glyphFor(raw);
    if (!g) {
      // 未知字符：画一个 1px 描边的空心方块
      ctx.fillRect(cx, y, GLYPH_W * scale, GLYPH_H * scale);
      ctx.clearRect(cx + scale, y + scale, (GLYPH_W - 2) * scale, (GLYPH_H - 2) * scale);
      cx += (GLYPH_W + 1) * scale;
      continue;
    }
    for (let row = 0; row < GLYPH_H; row++) {
      const bits = g[row]!;
      for (let col = 0; col < GLYPH_W; col++) {
        if (bits & (1 << (GLYPH_W - 1 - col))) {
          ctx.fillRect(cx + col * scale, y + row * scale, scale, scale);
        }
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
  return cx - x;
}

function drawArrow(
  ctx: CanvasRenderingContext2D,
  dir: 'up' | 'down' | 'left' | 'right',
  x: number,
  y: number,
  color: string,
  scale: number,
): void {
  ctx.fillStyle = color;
  const w = GLYPH_W * scale;
  const h = GLYPH_H * scale;
  const u = scale;
  if (dir === 'up') {
    ctx.fillRect(x + 2 * u, y, u, u);
    ctx.fillRect(x + u, y + u, 3 * u, u);
    ctx.fillRect(x, y + 2 * u, 5 * u, u);
    ctx.fillRect(x + 2 * u, y + 3 * u, u, h - 3 * u);
  } else if (dir === 'down') {
    ctx.fillRect(x + 2 * u, y + h - u, u, u);
    ctx.fillRect(x + u, y + h - 2 * u, 3 * u, u);
    ctx.fillRect(x, y + h - 3 * u, 5 * u, u);
    ctx.fillRect(x + 2 * u, y, u, h - 3 * u);
  } else if (dir === 'left') {
    ctx.fillRect(x, y + 2 * u, u, u);
    ctx.fillRect(x + u, y + u, u, 3 * u);
    ctx.fillRect(x + 2 * u, y, u, 5 * u);
    ctx.fillRect(x + 3 * u, y + 2 * u, w - 3 * u, u);
  } else {
    ctx.fillRect(x + w - u, y + 2 * u, u, u);
    ctx.fillRect(x + w - 2 * u, y + u, u, 3 * u);
    ctx.fillRect(x + w - 3 * u, y, u, 5 * u);
    ctx.fillRect(x, y + 2 * u, w - 3 * u, u);
  }
}
