/**
 * Token 同步器 —— 把 16-design-system 的 `--ds-*` 令牌层落地到本目录。
 *
 * 依据 16-design-system/MIGRATION-NOTES.md §1.1（路径 A/B）与 §2.5（19 号逐项替换表）。
 * 16 是**只读参考**，本项目不修改 16 的任何文件；同步器只读它的
 * `src/tokens.css` 与 `design-tokens.json`，并把结果写进本目录
 * `src/styles/tokens.css` 的生成区（两个哨兵注释之间）。
 *
 * 落地后本目录自包含：构建不依赖 16 存在。
 *
 * 用法：node scripts/sync-ds-tokens.mjs [--check]
 *   --check  只核对，不写入（CI 用）
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DS = path.resolve(ROOT, '..', '16-design-system');
const TARGET = path.join(ROOT, 'src/styles/tokens.css');

const BEGIN = '/* >>> DS-TOKENS:BEGIN (generated by scripts/sync-ds-tokens.mjs — do not edit) */';
const END = '/* <<< DS-TOKENS:END */';

const checkOnly = process.argv.includes('--check');
const errors = [];
const notes = [];

function readBlock(css, selector) {
  // 抓取一个选择器对应的完整 { ... } 块（考虑嵌套花括号）
  const idx = css.indexOf(selector);
  if (idx === -1) return null;
  const open = css.indexOf('{', idx);
  if (open === -1) return null;
  let depth = 0;
  for (let i = open; i < css.length; i += 1) {
    if (css[i] === '{') depth += 1;
    else if (css[i] === '}') {
      depth -= 1;
      if (depth === 0) return css.slice(open + 1, i);
    }
  }
  return null;
}

if (!fs.existsSync(path.join(DS, 'src/tokens.css'))) {
  console.error(`找不到参考实现：${path.join(DS, 'src/tokens.css')}`);
  console.error('16-design-system 是只读参考；本目录的 tokens.css 已包含上次落地结果，不同步也可构建。');
  process.exit(checkOnly ? 2 : 0);
}

const dsCss = fs.readFileSync(path.join(DS, 'src/tokens.css'), 'utf8');

/* ---- 1. 抽取 16 的 :root 令牌层 ------------------------------------- */
const rootBody = readBlock(dsCss, ':root {');
if (!rootBody) { console.error('未能从 16 的 tokens.css 解析 :root 块'); process.exit(1); }

/* ---- 2. 抽取深色主题与中文排版、reduced-motion ----------------------- */
const darkBody = readBlock(dsCss, '[data-ds-theme="dark"]');
const cjkStart = dsCss.indexOf(':lang(zh),');
const cjkEnd = dsCss.indexOf('/* ---------- 减少动态效果 ---------- */');
const cjkBlock = cjkStart !== -1 && cjkEnd > cjkStart ? dsCss.slice(cjkStart, cjkEnd).trim() : '';
const reducedStart = dsCss.indexOf('@media (prefers-reduced-motion: reduce)');
const reducedBlock = reducedStart !== -1 ? dsCss.slice(reducedStart).trim() : '';
if (!darkBody) errors.push('16 的 tokens.css 缺少 [data-ds-theme="dark"] 块');
if (!cjkBlock) errors.push('16 的 tokens.css 缺少 :lang(zh) 中文排版块');
if (!reducedBlock) errors.push('16 的 tokens.css 缺少 prefers-reduced-motion 块');

/* ---- 3. 与 design-tokens.json 交叉核对（V.3 机械判定口径） ---------- */
const tokensPath = path.join(DS, 'design-tokens.json');
if (fs.existsSync(tokensPath)) {
  const tokens = JSON.parse(fs.readFileSync(tokensPath, 'utf8'));
  const flat = [];
  (function walk(node, pathArr) {
    if (!node || typeof node !== 'object' || Array.isArray(node)) return;
    for (const [k, v] of Object.entries(node)) {
      if (k.startsWith('$')) continue;
      if (v && typeof v === 'object' && !Array.isArray(v) && !('$value' in v)) walk(v, [...pathArr, k]);
      else if (v && typeof v === 'object' && '$value' in v) flat.push({ path: [...pathArr, k].join('.'), node: v });
    }
  })(tokens, []);

  const kebab = (n) => n.replace(/[A-Z]/g, (ch) => '-' + ch.toLowerCase());
  // 归一化：引号风格（JSON 用单引号、CSS 用双引号）、小数尾零（0.10 ≡ 0.1）、
  // 空白与逗号后空格。等值不同名才判为不一致。
  const norm = (s) => String(s)
    .trim()
    .replace(/['"]/g, '"')
    .toLowerCase()
    .replace(/(\d*\.\d*?)0+(?![0-9])/g, '$1')
    .replace(/\.(\d*[^0-9\s])/g, '.$1')
    .replace(/\s+/g, ' ')
    .replace(/,\s*/g, ',')
    .replace(/;$/, '');

  /**
   * 16 的 src/tokens.css 是在 design-tokens.json 基础上**人工校订**过的，
   * 下列两处是校订结果而非偏差。本目录照抄 16 的 CSS 取值（与 16 自己的
   * tokens.css 逐字节一致），因此登记为已知差异，不判错。
   */
  const KNOWN_CALIBRATED_DELTAS = new Set([
    '--ds-font-mono',   // 16 在 JSON 基础上补了 Consolas（Windows 回退）
    '--ds-shadow-3',    // 0.10 与 0.1 等价，十六进制书写差异
  ]);

  // JSON 路径 → CSS 变量名（与 16 的 src/tokens.css 命名一致）
  const cssNameFor = (p) => {
    const [g, ...rest] = p;
    const last = rest[rest.length - 1];
    switch (g) {
      case 'color':   return `--ds-${kebab(last)}`;
      case 'space':   return `--ds-space-${last}`;
      case 'radius':  return `--ds-radius-${kebab(last)}`;
      case 'motion':
        if (rest[0] === 'duration') return `--ds-dur-${kebab(last)}`;
        if (rest[0] === 'easing') return `--ds-ease-${kebab(last)}`;
        return null;
      case 'zIndex':  return `--ds-z-${kebab(last)}`;
      case 'layout':  return `--ds-${kebab(last)}`;
      case 'typography':
        if (rest[0] === 'family') return `--ds-font-${kebab(last)}`;
        if (rest[0] === 'size') return `--ds-type-${kebab(last)}`;
        if (rest[0] === 'lineHeight') return `--ds-lh-${kebab(last)}`;
        if (rest[0] === 'weight') return `--ds-w-${kebab(last)}`;
        if (rest[0] === 'tracking') return `--ds-track-${kebab(last)}`;
        return null;
      case 'shadow':
        if (last === 'ring') return '--ds-ring';
        if (last === 'ringStrong') return '--ds-ring-strong';
        if (last === 'focusRing') return '--ds-focus-ring';
        return `--ds-shadow-${last}`;
      default: return null;
    }
  };

  const lightVars = new Map();
  for (const m of rootBody.matchAll(/(--ds-[a-z0-9-]+)\s*:\s*([^;]+);/gi)) lightVars.set(m[1], m[2].trim());
  const darkVars = new Map();
  for (const m of darkBody.matchAll(/(--ds-[a-z0-9-]+)\s*:\s*([^;]+);/gi)) darkVars.set(m[1], m[2].trim());

  const checked = [];
  const mismatched = [];
  const calibrated = [];
  const unresolved = [];

  for (const { path: p, node } of flat) {
    const parts = p.split('.');
    const cssName = cssNameFor(parts);
    if (!cssName) continue;
    const isDark = parts[0] === 'color' && parts[1] === 'dark';
    const table = isDark ? darkVars : lightVars;
    if (!table.has(cssName)) {
      // 该令牌在 16 的 CSS 中可能由其他路径承担或人工补足；记录但不判错
      unresolved.push(`${cssName} (${p})`);
      continue;
    }
    const cssValue = table.get(cssName);
    if (norm(cssValue) !== norm(node.$value)) {
      if (KNOWN_CALIBRATED_DELTAS.has(cssName)) {
        calibrated.push(`${cssName}: css="${cssValue}" json="${node.$value}"`);
      } else {
        mismatched.push(`${cssName}: css="${cssValue}" json="${node.$value}"`);
      }
    }
    checked.push(cssName);
  }

  notes.push(`与 design-tokens.json 交叉核对：${checked.length} 个令牌比对，${unresolved.length} 个在 CSS 中无同名变量`);
  if (calibrated.length) {
    notes.push(`  已知人工校准差异（16 的 tokens.css 权威值，照抄不判错）：${calibrated.length} 项`);
    for (const c of calibrated) notes.push(`    · ${c}`);
  }
  if (mismatched.length) {
    errors.push(`与 design-tokens.json 不一致（${mismatched.length}）：\n    ${mismatched.slice(0, 12).join('\n    ')}`);
  }
  if (unresolved.length) {
    notes.push(`  无同名 CSS 变量：${[...new Set(unresolved)].slice(0, 8).join(', ')}`);
  }
} else {
  notes.push('未找到 design-tokens.json，跳过交叉核对');
}

/* ---- 4. 组装生成区 --------------------------------------------------- */
/**
 * `rootBody` / `darkBody` are the *contents* of 16's blocks, without their
 * selectors. They must be re-wrapped here, or the generated declarations
 * land at the top level, the whole `:root` block is invalid CSS, and every
 * `--ds-*` token silently resolves to nothing — including `--ds-focus-ring`,
 * which would leave focusable elements with no visible focus indicator.
 */
const generated = [
  BEGIN,
  '',
  ':root {',
  rootBody.trim(),
  '}',
  '',
  '/* ---------- 深色主题 ---------- */',
  '/* [data-tone="dark"] 是 19 的分区调性反转（沿用 16 的同一组深色取值）。 */',
  '[data-ds-theme="dark"],',
  '[data-tone="dark"] {',
  darkBody.trim(),
  '}',
  '',
  '/* ---------- 跟随系统（未显式指定时） ---------- */',
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-ds-theme="light"]) {',
  darkBody.trim().split('\n').map((l) => `  ${l}`).join('\n'),
  '  }',
  '}',
  '',
  '/* ---------- 中文排版修正（负字距会破坏汉字字面） ---------- */',
  cjkBlock,
  '',
  '/* ---------- 减少动态效果 ---------- */',
  reducedBlock,
  END,
].join('\n');

/* ---- 5. 写回（保留别名区） ------------------------------------------- */
function spliceRegion(file, begin, end, region) {
  let current = '';
  if (fs.existsSync(file)) current = fs.readFileSync(file, 'utf8');
  const beginIdx = current.indexOf(begin);
  const endIdx = current.indexOf(end);
  let next;
  if (beginIdx !== -1 && endIdx !== -1) {
    next = current.slice(0, beginIdx) + region + current.slice(endIdx + end.length);
  } else {
    next = `${region}\n\n${current}`;
  }
  return { current, next };
}

/**
 * Guard: the generated region must open with a `:root {` block. A missing
 * wrapper makes every `--ds-*` declaration invalid CSS, and the whole token
 * layer then resolves to nothing at run time — a failure that no build step
 * reports and that only shows up as an invisible focus ring.
 */
if (!/:root\s*\{/.test(generated.split('\n').slice(0, 4).join('\n'))) {
  errors.push('生成区缺少 :root { 包裹 —— 令牌层会整体失效');
}

const t = spliceRegion(TARGET, BEGIN, END, generated);

/* ---- 5b. 组件层：把 16 的 .ds-* 类落地（供外壳换装用） -------------- */
const DS_COMPONENTS = path.join(DS, 'src/components.css');
const COMPONENTS_TARGET = path.join(ROOT, 'src/styles/components.css');
const C_BEGIN = '/* >>> DS-COMPONENTS:BEGIN (generated by scripts/sync-ds-tokens.mjs — do not edit) */';
const C_END = '/* <<< DS-COMPONENTS:END */';
let componentsRegion = '';
if (fs.existsSync(DS_COMPONENTS)) {
  const dsComponents = fs.readFileSync(DS_COMPONENTS, 'utf8');
  const body = dsComponents.slice(dsComponents.indexOf('*/') + 2).trim();
  componentsRegion = [C_BEGIN, '', body, '', C_END].join('\n');
  const c = spliceRegion(COMPONENTS_TARGET, C_BEGIN, C_END, componentsRegion);
  if (checkOnly) {
    if (c.next !== c.current) { errors.push('src/styles/components.css 与 16 的组件层不一致'); }
  } else {
    fs.writeFileSync(COMPONENTS_TARGET, c.next);
    notes.push(`组件类层：${body.split('\n').length} 行 → src/styles/components.css`);
  }
}

/* ---- 6. 输出 --------------------------------------------------------- */
if (checkOnly) {
  const same = t.next === t.current;
  console.log(same ? '✅ tokens.css 与 16 的令牌层一致' : '❌ tokens.css 与 16 的令牌层不一致，请运行 node scripts/sync-ds-tokens.mjs');
  notes.forEach((n) => console.log(`   ${n}`));
  errors.forEach((e) => console.error(`   ✗ ${e}`));
  process.exit(same && !errors.length ? 0 : 1);
}

fs.writeFileSync(TARGET, t.next);
console.log(`✅ 已更新 ${path.relative(ROOT, TARGET)}`);
notes.forEach((n) => console.log(`   ${n}`));
console.log(`   落地 ${generated.split('\n').length} 行生成区`);
if (errors.length) {
  errors.forEach((e) => console.error(`   ✗ ${e}`));
  process.exit(1);
}
