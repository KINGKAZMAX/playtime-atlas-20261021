const FALLBACK = ['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'];

/**
 * 把文本绘制到 2D 上下文（像素对齐）。
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} text
 * @param {number} x
 * @param {number} y
 * @param {object} opts { color, scale, spacing, align }
 */
export function drawPixelText(ctx, text, x, y, opts = {}) {
  const {
    color = '#f4efe4',
    scale = 1,
    spacing = 1,
    align = 'left',
    shadow = null,
  } = opts;

  const chars = String(text).toUpperCase().split('');
  const cellW = GLYPH_W + spacing;
  const totalW = chars.length * cellW * scale - spacing * scale;
  let ox = x;
  if (align === 'center') ox = Math.round(x - totalW / 2);
  else if (align === 'right') ox = Math.round(x - totalW);
  ox = Math.round(ox);
  const oy = Math.round(y);

  const paint = (dx, dy, fill) => {
    ctx.fillStyle = fill;
    chars.forEach((ch, i) => {
      const glyph = G[ch] || FALLBACK;
      const gx = ox + i * cellW * scale + dx;
      for (let r = 0; r < GLYPH_H; r++) {
        const row = glyph[r];
        for (let c = 0; c < GLYPH_W; c++) {
          if (row[c] === '#') ctx.fillRect(gx + c * scale, oy + r * scale + dy, scale, scale);
        }
      }
    });
  };

  if (shadow) paint(scale, scale, shadow);
  paint(0, 0, color);
  return totalW;
}

/** 文本像素宽度（用于布局） */
export function measurePixelText(text, scale = 1, spacing = 1) {
  const chars = String(text).length;
  return chars * (GLYPH_W + spacing) * scale - spacing * scale;
}

/** 渲染成独立 canvas（用于 Logo） */
export function renderPixelTextCanvas(text, opts = {}) {
  const { scale = 4, spacing = 1, color = '#f4efe4', shadow = null, padding = 4 } = opts;
  const w = measurePixelText(text, scale, spacing) + padding * 2;
  const h = GLYPH_H * scale + padding * 2;
  const cv = document.createElement('canvas');
  cv.width = Math.max(1, w);
  cv.height = Math.max(1, h);
  const ctx = cv.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  drawPixelText(ctx, text, padding, padding, { scale, spacing, color, shadow });
  return cv;
}

