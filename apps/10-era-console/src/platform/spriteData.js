/** 校验一组精灵行宽一致；返回问题列表（测试用） */
export function validateSprites(sprites) {
  const issues = [];
  for (const [name, rows] of Object.entries(sprites)) {
    if (!Array.isArray(rows) || rows.length === 0) {
      issues.push(`${name}: 不是有效的精灵数组`);
      continue;
    }
    const w = rows[0].length;
    rows.forEach((row, i) => {
      if (row.length !== w) {
        issues.push(`${name}[${i}]: 宽度 ${row.length} ≠ 首行宽度 ${w}`);
      }
      // 允许 '.' 与 '0' 表示透明，其余必须是 1-8 的调色板索引
      if (/[^0-8.]/.test(row)) {
        issues.push(`${name}[${i}]: 含非法调色板字符`);
      }
    });
  }
  return issues;
}

